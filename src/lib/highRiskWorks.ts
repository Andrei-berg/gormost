/** Категории повышенной опасности, под которые подпадает текст работы. */
export function matchedHighRiskCategories(text: string): HighRiskCategory[] {
  const t = norm(text)
  if (!t.trim()) return []
  return HIGH_RISK_CATEGORIES.filter(cat => cat.keywords.some(k => t.includes(norm(k))))
}

/** Требует ли работа оформления наряда-допуска (п.15). */
export function requiresWorkPermit(text: string): boolean {
  return matchedHighRiskCategories(text).length > 0
}
