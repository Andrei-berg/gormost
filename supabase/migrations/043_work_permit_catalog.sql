-- Каталог видов работ для наряда-допуска (этап «универсальный редактируемый каталог»).
-- WHY: сейчас виды работ захардкожены в WorkPermitModal (WORK_TYPES_BY_SERVICE).
-- Выносим в БД, чтобы нач. служб могли курировать/править/удалять без правок кода.
--
-- Модель: ЕДИНЫЙ универсальный каталог видов (work_permit_types) +
-- курирование по службе (work_permit_service_types: какие виды включены службе
-- и опциональные переопределения формулировок). «Удалить ненужное» = убрать из
-- набора своей службы; глобально add/delete — ОТ/админ.
--
-- Этот сид переносит ТЕКУЩИЙ контент 1:1: СЭИС (11 видов из кода) + ЭНГ (3 вида,
-- разобраны из эталонов). Поведение прода не меняется — модалка просто начнёт
-- читать те же данные из БД. Факторы — редактируемый дефолт; № инструкций для
-- остальных служб (FIRE/VENT/CCTV) заполняет нач. службы (внутренний реестр).

-- ── Универсальный каталог видов работ ──────────────────────────────────────
create table if not exists work_permit_types (
  id                text primary key,            -- стабильный слаг
  label             text not null,
  factors           text not null default '',    -- опасные производственные факторы (дефолт)
  instruction_nums  text not null default '',    -- № инструкций ОТ (внутр. реестр Гормоста)
  is_road_work      boolean not null default false, -- работы на проезжей части (маячки/ГИБДД)
  during_measure_2  text not null default 'Соблюдать технологию выполнения работ.',
  sort_order        smallint not null default 0,
  is_active         boolean not null default true,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- ── Курирование по службе ──────────────────────────────────────────────────
create table if not exists work_permit_service_types (
  service_id                text not null references services(service_id),
  type_id                   text not null references work_permit_types(id) on delete cascade,
  enabled                   boolean not null default true,
  -- service-override: null = брать значение из каталога
  factors_override          text,
  instruction_nums_override text,
  during_measure_2_override text,
  sort_order                smallint not null default 0,
  primary key (service_id, type_id)
);

